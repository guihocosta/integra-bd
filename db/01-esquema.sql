/* Integra: esquema do banco (PostgreSQL), a partir do Modelo-logico_Integra-v1 */

CREATE TABLE PPC (
    data DATE NOT NULL,
    semestre_ativo VARCHAR(50) NOT NULL,
    id INTEGER PRIMARY KEY,
    pontos_minimos INTEGER NOT NULL,
    CONSTRAINT CK_PPC_pontos CHECK (pontos_minimos > 0)
);

CREATE TABLE EIXO (
    id INTEGER PRIMARY KEY,
    descricao VARCHAR(150) NOT NULL,
    limite_pontos INTEGER NOT NULL,
    PPC_id INTEGER NOT NULL,
    CONSTRAINT CK_EIXO_limite CHECK (limite_pontos > 0)
);

CREATE TABLE TIPO_DE_ATIVIDADE (
    id INTEGER PRIMARY KEY,
    descricao VARCHAR(150) NOT NULL,
    pontos_por_unidade INTEGER NOT NULL,
    unidade VARCHAR(150) NOT NULL,
    exige_relacao_curso BOOLEAN NOT NULL,
    ativo BOOLEAN NOT NULL,
    EIXO_id INTEGER NOT NULL,
    CONSTRAINT CK_TIPO_pontos CHECK (pontos_por_unidade > 0)
);

CREATE TABLE SERVIDOR_PEDAGOGICO (
    matricula VARCHAR(50) PRIMARY KEY,
    nome VARCHAR(150) NOT NULL
);

CREATE TABLE ESTUDANTE (
    matricula VARCHAR(50) PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    data_ingresso DATE NOT NULL,
    situacao_matricula VARCHAR(50) NOT NULL,
    PPC_id INTEGER NOT NULL,
    SERVIDOR_PEDAGOGICO_matricula VARCHAR(50),
    data_lancamento DATE,
    -- o lançamento tem servidor e data juntos, ou nenhum dos dois
    CONSTRAINT CK_ESTUDANTE_lancamento CHECK (
        (SERVIDOR_PEDAGOGICO_matricula IS NULL) = (data_lancamento IS NULL)
    )
);

CREATE TABLE AVALIADOR (
    setor VARCHAR(50) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    matricula VARCHAR(50) PRIMARY KEY,
    email VARCHAR(150) NOT NULL,
    ativo BOOLEAN NOT NULL
);

CREATE TABLE MANDATO (
    data_inicio DATE NOT NULL,
    data_fim DATE,
    AVALIADOR_matricula VARCHAR(50) NOT NULL,
    id INTEGER PRIMARY KEY,
    CONSTRAINT CK_MANDATO_datas CHECK (data_fim >= data_inicio)
);

CREATE TABLE JANELA_DE_AVALIACAO (
    semestre VARCHAR(50) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    id INTEGER PRIMARY KEY,
    MANDATO_id INTEGER NOT NULL,
    CONSTRAINT CK_JANELA_datas CHECK (data_fim >= data_inicio)
);

CREATE TABLE PEDIDO_DE_AVALIACAO (
    id INTEGER PRIMARY KEY,
    data_abertura DATE NOT NULL,
    data_conclusao DATE,
    status VARCHAR(50) NOT NULL,
    ESTUDANTE_matricula VARCHAR(50) NOT NULL,
    JANELA_DE_AVALIACAO_id INTEGER NOT NULL,
    CONSTRAINT CK_PEDIDO_status CHECK (status IN ('ABERTO', 'CONCLUIDO', 'PENDENTE')),
    CONSTRAINT CK_PEDIDO_datas CHECK (data_conclusao >= data_abertura)
);

CREATE TABLE ATIVIDADE (
    data_cadastro DATE NOT NULL,
    declarou_nao_uso BOOLEAN NOT NULL,
    status VARCHAR(50) NOT NULL,
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(150) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    quantidade_unidades INTEGER NOT NULL,
    TIPO_DE_ATIVIDADE_id INTEGER NOT NULL,
    ESTUDANTE_matricula VARCHAR(50) NOT NULL,
    PEDIDO_DE_AVALIACAO_id INTEGER,
    -- tipo e quantidade confirmados ficam nulos quando o avaliador mantém o que o estudante informou
    TIPO_DE_ATIVIDADE_CONFIRMADA_id INTEGER,
    quantidade_confirmada INTEGER,
    CONSTRAINT CK_ATIVIDADE_status CHECK (status IN ('CADASTRADA', 'EM_AVALIACAO', 'APROVADA', 'REJEITADA')),
    CONSTRAINT CK_ATIVIDADE_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT CK_ATIVIDADE_quantidade CHECK (quantidade_unidades > 0),
    CONSTRAINT CK_ATIVIDADE_quantidade_confirmada CHECK (quantidade_confirmada >= 0)
);

CREATE TABLE COMPROVANTE (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_arquivo VARCHAR(150) NOT NULL,
    hash VARCHAR(150) NOT NULL,
    path_arquivo VARCHAR(150) NOT NULL,
    data_envio DATE NOT NULL,
    ATIVIDADE_id INTEGER NOT NULL,
    CONSTRAINT UN_COMPROVANTE_atividade UNIQUE (ATIVIDADE_id)
);

CREATE TABLE AVALIACAO (
    data DATE,
    resultado VARCHAR(50),
    justificativa VARCHAR(150),
    id INTEGER PRIMARY KEY,
    status VARCHAR(50) NOT NULL,
    ATIVIDADE_id INTEGER NOT NULL,
    AVALIADOR_matricula VARCHAR(50) NOT NULL,
    CONSTRAINT UN_AVALIACAO_atividade UNIQUE (ATIVIDADE_id),
    CONSTRAINT CK_AVALIACAO_resultado CHECK (resultado IN ('APROVADA', 'REJEITADA')),
    -- em andamento ainda não tem data nem resultado; finalizada tem os dois
    CONSTRAINT CK_AVALIACAO_status CHECK (
        (status = 'EM_ANDAMENTO' AND data IS NULL AND resultado IS NULL)
        OR (status = 'FINALIZADA' AND data IS NOT NULL AND resultado IS NOT NULL)
    )
);

